"""Unit and regression tests for continuous infinite WAV streaming handoff (RADIO-006C).

Validates:
1. Mathematical precision and architectural proof of the 22,826.051338-second invariant:
   - Liquidsoap 2.2.4 hardcoded data_len = 0xEFFFFFDB (4,026,531,803 bytes) from wav_aiff.ml.
   - Liquidsoap 2.2.4 hardcoded RIFF length = 0xEFFFFFFF (4,026,531,839 bytes = data_len + 36).
   - Stereo signed 16-bit PCM (4 bytes/sample) -> 1,006,632,950 total audio samples.
   - AAC 1024-sample frames -> 983,039 complete frames + 1,014 samples remainder.
   - AAC encoder internal pipeline buffer (libavcodec/aacenc.c:1234, s->planar_samples = 3 * 1024 = 3072 samples):
     initial_padding (1024 samples) + psychoacoustic MDCT window lookahead.
   - When WAV demuxer hits 0xEFFFFFDB, libavformat/wavdec.c:770 enters find_tag() on the live HTTP socket.
     Because the live socket never closes, av_read_frame() never returns EOF.
   - Without EOF, AAC encoder flush (frame = NULL) is never called; the 3 buffered frames remain unflushed.
   - Last muxed packet emitted is frame index 983,036:
     983,036 * 1024 = 1,006,628,864 samples = 4,026,515,456 bytes (0xEFFFC000).
   - FFTools progress calculation (fftools/ffmpeg_mux.c:357):
     av_rescale_q(1006628864, {1, 44100}, {1, 1000000}) = 22826051338 microseconds.
   - Exact match to historical production watchdog stall: out_time_us = 22826051338.
2. P2 Test Harness: Verified constructed stream.sh FFmpeg argv order via argument-recording stub.
3. Accelerated offline reproduction with real FFmpeg and machine-readable progress assertion:
   - Captures out_time_us boundary stall without -ignore_length 1.
   - Verifies continuous streaming past boundary to completion with -ignore_length 1.
"""
